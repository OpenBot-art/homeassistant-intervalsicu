@dataclass(frozen=True, kw_only=True)
class IntervalsIcuSensorEntityDescription(SensorEntityDescription):
    """Describe an Intervals.icu sensor."""

    value_fn: Callable[[IntervalsIcuData], Any]
    available_fn: Callable[[IntervalsIcuData], bool] = lambda _data: True
    attrs_fn: Callable[[IntervalsIcuData], dict[str, Any] | None] | None = None


def _wellness_value(key: str) -> Callable[[IntervalsIcuData], Any]:
    """Create a value function for a wellness field."""

    def _get(data: IntervalsIcuData) -> Any:
        if data.wellness is None:
            return None
        return data.wellness.get(key)

    return _get


def _wellness_available(key: str) -> Callable[[IntervalsIcuData], bool]:
    """Create an available function for a wellness field."""

    def _check(data: IntervalsIcuData) -> bool:
        if data.wellness is None:
            return False
        return data.wellness.get(key) is not None

    return _check


def _latest_activity_value(key: str) -> Callable[[IntervalsIcuData], Any]:
    """Create a value function for the latest activity field.

    ``data.latest_activity`` is guaranteed to be the newest record because the
    coordinator sorts activities explicitly rather than trusting the API order.
    """

    def _get(data: IntervalsIcuData) -> Any:
        activity = data.latest_activity
        if activity is None:
            return None
        return activity.get(key)

    return _get


def _latest_activity_available(data: IntervalsIcuData) -> bool:
    return data.latest_activity is not None


def _next_event_value(key: str) -> Callable[[IntervalsIcuData], Any]:
    """Create a value function for the next planned workout."""

    def _get(data: IntervalsIcuData) -> Any:
        workout = data.next_workout
        if workout is None:
            return None
        return workout.get(key)

    return _get


def _next_event_available(data: IntervalsIcuData) -> bool:
    return data.next_workout is not None


def _form_value(data: IntervalsIcuData) -> float | None:
    """Calculate form (TSB) = CTL - ATL."""
    if data.wellness is None:
        return None
    ctl = data.wellness.get("ctl")
    atl = data.wellness.get("atl")
    if ctl is None or atl is None:
        return None
    return round(ctl - atl, 1)


def _form_available(data: IntervalsIcuData) -> bool:
    """Check if form can be calculated."""
    if data.wellness is None:
        return False
    return data.wellness.get("ctl") is not None and data.wellness.get("atl") is not None


def _athlete_value(key: str) -> Callable[[IntervalsIcuData], Any]:
    """Create a value function for an athlete top-level field."""

    def _get(data: IntervalsIcuData) -> Any:
        return data.athlete.get(key)

    return _get


def _sport_setting_value(key: str) -> Callable[[IntervalsIcuData], Any]:
    """Create a value function for a field in the default sport settings.

    Kept for backwards compatibility with the athlete profile sensors that
    describe whichever sport settings entry the API lists first. Per-sport
    sensors are generated by ``_sport_setting_sensors`` instead.
    """

    def _get(data: IntervalsIcuData) -> Any:
        settings = data.athlete.get("sportSettings")
        if not settings:
            return None
        return settings[0].get(key)

    return _get


def _sport_setting_available(key: str) -> Callable[[IntervalsIcuData], bool]:
    """Create an available function for a field in the default sport settings."""

    def _check(data: IntervalsIcuData) -> bool:
        settings = data.athlete.get("sportSettings")
        if not settings:
            return False
        return settings[0].get(key) is not None

    return _check


def _sport_setting_sports(data: IntervalsIcuData) -> list[tuple[str, dict[str, Any]]]:
    """Return ``(sport_type, settings)`` pairs in a stable order.

    ``sportSettings`` holds one entry per sport (Ride, Run, Swim, ...), each
    with its own FTP, LTHR and max HR. Reading only ``sportSettings[0]`` means
    a multi-sport athlete silently loses every sport but the first. Enumerating
    all of them produces one set of sensors per sport instead.
    """
    settings = data.athlete.get("sportSettings") or []
    pairs: list[tuple[str, dict[str, Any]]] = []
    for entry in settings:
        if not isinstance(entry, dict):
            continue
        sport = entry.get("type") or entry.get("sport") or "Default"
        pairs.append((str(sport), entry))
    pairs.sort(key=lambda pair: pair[0])
    return pairs


def _sport_setting_value_for(
    sport: str, key: str
) -> Callable[[IntervalsIcuData], Any]:
    """Create a value function for a specific sport's settings field."""

    def _get(data: IntervalsIcuData) -> Any:
        for name, entry in _sport_setting_sports(data):
            if name == sport:
                return entry.get(key)
        return None

    return _get


def _sport_setting_available_for(
    sport: str, key: str
) -> Callable[[IntervalsIcuData], bool]:
    """Create an available function for a specific sport's settings field."""

    def _check(data: IntervalsIcuData) -> bool:
        for name, entry in _sport_setting_sports(data):
            if name == sport:
                return entry.get(key) is not None
        return False

    return _check


