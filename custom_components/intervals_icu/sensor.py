def localize_sport(sport: str, language: str | None = None) -> str:
    """Return a display label for a sport type.

    Only Simplified and Traditional Chinese labels are provided; every other
    language falls back to the raw API value, which is already the English
    spelling used by Intervals.icu.
    """
    if language is None:
        return SPORT_DISPLAY_NAMES.get(sport, sport)
    if language.startswith("zh-Hant") or language.startswith("zh-TW"):
        return SPORT_DISPLAY_NAMES_HANT.get(
            sport, SPORT_DISPLAY_NAMES.get(sport, sport)
        )
    if language.startswith("zh"):
        return SPORT_DISPLAY_NAMES.get(sport, sport)
    return sport


def _slugify(value: str) -> str:
    """Lowercase a sport name into a stable identifier fragment."""
    return "".join(ch if ch.isalnum() else "_" for ch in value.lower()).strip("_")


_NAMED_DISTANCES: tuple[tuple[float, str], ...] = (
    (1609.34, "1 mile"),
    (3218.69, "2 miles"),
    (5000.0, "5k"),
    (10000.0, "10k"),
    (16093.4, "10 miles"),
    (21097.5, "half marathon"),
    (42195.0, "marathon"),
)


def _format_distance(meters: float) -> str:
    """Format a distance in meters as a short human-readable label."""
    for value, label in _NAMED_DISTANCES:
        if abs(meters - value) < 1.0:
            return label
    if meters >= 1000:
        km = meters / 1000
        if km == int(km):
            return f"{int(km)}k"
        return f"{km:g}k"
    return f"{round(meters)}m"


def _best_effort_value(index: int) -> Callable[[IntervalsIcuData], Any]:
    """Create a value function for the best effort at a distance index."""

    def _get(data: IntervalsIcuData) -> Any:
        curve = data.pace_curve
        if not curve:
            return None
        values = curve.get("values") or []
        if index >= len(values):
            return None
        return values[index]

    return _get


def _best_effort_available(index: int) -> Callable[[IntervalsIcuData], bool]:
    """Return True when the pace curve has a value at the given index."""

    def _check(data: IntervalsIcuData) -> bool:
        curve = data.pace_curve
        if not curve:
            return False
        values = curve.get("values") or []
        return index < len(values) and values[index] is not None

    return _check


def _best_effort_attrs(
    index: int,
) -> Callable[[IntervalsIcuData], dict[str, Any] | None]:
    """Return the activity id/name/date that set the best effort at this index."""

    def _get(data: IntervalsIcuData) -> dict[str, Any] | None:
        curve = data.pace_curve
        if not curve:
            return None
        activity_ids = curve.get("activity_id") or []
        if index >= len(activity_ids):
            return None
        activity_id = activity_ids[index]
        return {"activity_id": activity_id}

    return _get


