def _sport_setting_sensors(
    data: IntervalsIcuData,
) -> tuple[IntervalsIcuSensorEntityDescription, ...]:
    """Build one FTP/LTHR/max HR sensor set per configured sport.

    ``unique_id`` and the display name both carry the sport type so that a
    multi-sport athlete (for example cycling with FTP 280 W and running with
    FTP 250 W) gets a distinct, unambiguous sensor for each instead of only
    ever seeing whichever entry the API returned first.

    The sport is passed to the translation as a ``sport`` placeholder. The
    entity ID is built from the raw API sport name via ``_slugify`` so it stays
    stable if the displayed translation ever changes.
    """
    descriptions: list[IntervalsIcuSensorEntityDescription] = []
    for sport, _settings in _sport_setting_sports(data):
        slug = _slugify(sport)
        for field_key, unit, device_class, translation_key in _SPORT_FIELDS:
            kwargs: dict[str, Any] = {
                "key": f"{field_key}_{slug}",
                "translation_key": translation_key,
                "translation_placeholders": {"sport": sport},
                "name": f"{sport} {field_key.upper().replace('_', ' ')}",
                "native_unit_of_measurement": unit,
                "state_class": SensorStateClass.MEASUREMENT,
                "value_fn": _sport_setting_value_for(sport, field_key),
                "available_fn": _sport_setting_available_for(sport, field_key),
            }
            if device_class is not None:
                kwargs["device_class"] = device_class
            descriptions.append(IntervalsIcuSensorEntityDescription(**kwargs))
    return tuple(descriptions)


